/// Le champ « Code » n'apparaît que pour le compte qui l'a demandé, et le code ne part qu'une fois.
@MainActor
final class MegaCodeModelTests: XCTestCase {
    func testCodeFieldAppearsAfterTheRequestAndFeedsTheNextConnection() async {
        let suite = "FilTests.MegaCode"
        UserDefaults().removePersistentDomain(forName: suite)
        let defaults = UserDefaults(suiteName: suite)!
        defer { defaults.removePersistentDomain(forName: suite) }
        let fake = FakeMega { command, arguments in
            if command == "whoami" { return fail("Not logged in.") }
            if command == "login" { return arguments.first == "--auth-code=123456" ? ok() : ok("Enter the code generated by your authentication app: ") }
            return ok()
        }
        let secrets = MemorySecretStore()
        let model = AppModel(store: ConnectionStore(defaults: defaults), preferences: Preferences(defaults: defaults), secrets: secrets) { connection, password in
            MegaProvider(connection: connection, password: password, runner: fake)
        }
        model.addConnection()
        let id = model.selectedConnectionID!
        model.updateProtocol(id, to: .mega)
        model.updateConnection(id) { $0.username = "moi@exemple.fr" }
        model.passwordDraft = "secret"
        XCTAssertNil(model.oneTimeCodeRequestedFor)
        model.connect()
        await waitUntil("code demandé") { model.oneTimeCodeRequestedFor == id }
        guard case .failed = model.phase else { return XCTFail("La connexion doit attendre le code") }

        model.oneTimeCodeDraft = "123 456"
        model.connect()
        await waitUntil("ouverte") { model.phase.isBrowsing }
        XCTAssertNil(model.oneTimeCodeRequestedFor)
        XCTAssertEqual(model.oneTimeCodeDraft, "")
    }
}
