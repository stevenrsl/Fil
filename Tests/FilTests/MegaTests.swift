@testable import Fil

/// Faux MEGAcmd : chaque commande reçoit une réponse écrite par le test, et les appels sont notés.
private final class FakeMega: MegaCommandRunning, @unchecked Sendable {
    typealias Reply = (_ command: String, _ arguments: [String]) -> ProcessRunner.CapturedOutput
    private let lock = NSLock()
    private var _calls: [[String]] = []
    let reply: Reply

    init(_ reply: @escaping Reply) { self.reply = reply }

    var calls: [[String]] { lock.withLock { _calls } }


    var restarts = 0
    /// Nombre de premiers `whoami` qui tombent en délai dépassé, comme un serveur figé.
    var frozenWhoami = 0

    func restartServer() async { lock.withLock { restarts += 1 } }

    func run(_ command: String, _ arguments: [String], timeout: Duration) async throws -> ProcessRunner.CapturedOutput {
        lock.withLock { _calls.append([command] + arguments) }
        if command == "whoami", lock.withLock({ () -> Bool in defer { frozenWhoami -= 1 }; return frozenWhoami > 0 }) { throw ProviderError.timedOut }
        return reply(command, arguments)
    }
}

private func ok(_ out: String = "") -> ProcessRunner.CapturedOutput { .init(status: 0, standardOutput: out, errorOutput: "") }
private func fail(_ err: String) -> ProcessRunner.CapturedOutput { .init(status: 1, standardOutput: "", errorOutput: err) }

final class MegaTests: XCTestCase {
    private let connection = RemoteConnection(name: "MEGA", protocol: .mega, username: "moi@exemple.fr")

    func testModelNeedsAnEmailButNoServerAddress() {
        var mega = RemoteConnection(protocol: .mega)
        XCTAssertFalse(RemoteProtocol.mega.hasServerAddress)
        XCTAssertEqual(mega.resolvedHost, "")
        XCTAssertEqual(Readiness.connecting(mega).reasons, ["Ajoute l'adresse e-mail de ton compte MEGA."])
        mega.username = "moi@exemple.fr"
        XCTAssertTrue(Readiness.connecting(mega).isReady)
        XCTAssertEqual(mega.summary, "MEGA · moi@exemple.fr")
    }

    func testListingParsesLongFormat() {
        let output = """
        FLAGS VERS          SIZE                DATE      NAME
        d---     -             -  2026-11-20T22:25:03      Cloud de Steven
        ----     1       1048576  2026-11-21T08:00:00      rapport final.pdf
        -ep-     3            12  21Nov2026 09:30:00       notes.txt
        garbage line
        """
        let files = MegaProvider.files(from: output, parent: RemotePath("/Travail"))
        XCTAssertEqual(files.map(\.name), ["Cloud de Steven", "rapport final.pdf", "notes.txt"])
        XCTAssertTrue(files[0].isDirectory)
        XCTAssertNil(files[0].byteCount)
        XCTAssertEqual(files[1].byteCount, 1_048_576)
        XCTAssertEqual(files[1].path.value, "/Travail/rapport final.pdf")
        XCTAssertNotNil(files[1].modifiedAt)
        XCTAssertNotNil(files[2].modifiedAt)
    }

    func testReusesTheSessionOfTheSameAccount() async throws {
        let fake = FakeMega { command, _ in command == "whoami" ? ok("Account e-mail: Moi@Exemple.fr\n") : ok() }
        let start = try await MegaProvider(connection: connection, password: "", runner: fake).connect()
        XCTAssertEqual(start, .root)
        XCTAssertFalse(fake.calls.contains { $0.first == "login" })
    }

    func testAFrozenServerIsRestartedOnce() async throws {
        let fake = FakeMega { command, _ in command == "whoami" ? ok("Account e-mail: moi@exemple.fr") : ok() }
        fake.frozenWhoami = 1
        _ = try await MegaProvider(connection: connection, password: "", runner: fake).connect()
        XCTAssertEqual(fake.restarts, 1)
        XCTAssertEqual(fake.calls.filter { $0.first == "whoami" }.count, 2)
    }

    func testLogsInWithTheKeychainPasswordWhenLoggedOut() async throws {
        let fake = FakeMega { command, _ in command == "whoami" ? fail("[err: 12:00:00] Not logged in.") : ok() }
        _ = try await MegaProvider(connection: connection, password: "secret", runner: fake).connect()
        XCTAssertEqual(fake.calls.first { $0.first == "login" }, ["login", "moi@exemple.fr", "secret"])
    }

    func testOtherAccountAndTwoFactorAreExplained() async {
        let other = FakeMega { _, _ in ok("Account e-mail: autre@exemple.fr") }
        do {
            _ = try await MegaProvider(connection: connection, password: "x", runner: other).connect()
            XCTFail("Un autre compte ne doit pas être utilisé")
        } catch {
            XCTAssertTrue(error.localizedDescription.contains("autre@exemple.fr"))
        }
        let twoFactor = FakeMega { command, _ in command == "whoami" ? fail("Not logged in.") : ok("Enter the code generated by your authentication app: ") }
        do {
            _ = try await MegaProvider(connection: connection, password: "x", runner: twoFactor).connect()
            XCTFail("La double authentification doit être demandée")
        } catch {
            XCTAssertEqual(error as? ProviderError, .oneTimeCodeRequired(service: "MEGA", rejected: false))
        }
        let refused = FakeMega { command, _ in command == "whoami" ? fail("Not logged in.") : fail("Login failed: Failed access") }
        do {
            _ = try await MegaProvider(connection: connection, password: "x", runner: refused).connect()
            XCTFail("Un mot de passe refusé doit échouer")
        } catch {
            XCTAssertEqual(error as? ProviderError, .authenticationFailed)
        }
    }

    func testTypedCodeGoesToLoginOnceAndAWrongOneIsSaid() async throws {
        let fake = FakeMega { command, arguments in
            if command == "whoami" { return fail("Not logged in.") }
            if command == "login" { return arguments.first == "--auth-code=123456" ? ok("Login complete as moi@exemple.fr") : fail("Login failed: incorrect authentication") }
            return ok()
        }
        let provider = MegaProvider(connection: connection, password: "secret", runner: fake)
        provider.useOneTimeCode("654321")
        do {
            _ = try await provider.connect()
            XCTFail("Un mauvais code doit échouer")
        } catch {
            XCTAssertEqual(error as? ProviderError, .oneTimeCodeRequired(service: "MEGA", rejected: true))
        }
        provider.useOneTimeCode("123456")
        _ = try await provider.connect()
        XCTAssertEqual(fake.calls.filter { $0.first == "login" }.last, ["login", "--auth-code=123456", "moi@exemple.fr", "secret"])
    }

    func testSignatureCheckRejectsAnythingButMegaLimited() throws {
        XCTAssertFalse(MegaCMDInstaller.isGenuine(URL(fileURLWithPath: "/System/Applications/Calculator.app")))
        XCTAssertFalse(MegaCMDInstaller.isGenuine(URL(fileURLWithPath: "/nonexistent/MEGAcmd.app")))
        guard let path = ProcessInfo.processInfo.environment["FIL_TEST_MEGACMD_APP"] else { throw XCTSkip("Chemin d'un vrai MEGAcmd.app requis") }
        XCTAssertTrue(MegaCMDInstaller.isGenuine(URL(fileURLWithPath: path)))
    }

    func testDownloadLandsNextToItsDestinationThenRenames() async throws {
        let folder = FileManager.default.temporaryDirectory.appendingPathComponent("FilMega-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: folder) }
        let fake = FakeMega { command, arguments in
            switch command {
            case "get":
                XCTAssertEqual(Array(arguments.prefix(2)), ["-q", "--print-tag-at-start"])
                let landing = URL(fileURLWithPath: arguments[3])
                XCTAssertEqual(landing.deletingLastPathComponent().standardizedFileURL, folder.standardizedFileURL)
                try? Data("bonjour".utf8).write(to: landing.appendingPathComponent("a.txt"))
                return ok("Download started: Tag = 9\n")
            case "transfers": return ok("TAG|PROGRESS|STATE\n9|100.00% of 7 B|COMPLETED\n")
            default: return ok()
            }
        }
        let provider = MegaProvider(connection: connection, password: "", runner: fake, poll: .milliseconds(5))
        let destination = folder.appendingPathComponent("a.txt.filpart")
        try await provider.download(RemoteFile(name: "a.txt", path: RemotePath("/a.txt"), kind: .file, byteCount: 7), to: destination, resumingAt: 0) { _ in }
        XCTAssertEqual(try String(contentsOf: destination, encoding: .utf8), "bonjour")
        XCTAssertEqual(try FileManager.default.contentsOfDirectory(atPath: folder.path), ["a.txt.filpart"])
    }

    func testMoveOntoAnExistingNameNeverLeavesADuplicate() async throws {
        let listing = "----  1  5  2026-11-21T08:00:00  site.zip\n----  1  5  2026-11-21T08:00:00  site.zip.filpart\n"
        let fake = FakeMega { command, _ in command == "ls" ? ok(listing) : ok() }
        try await MegaProvider(connection: connection, password: "", runner: fake).move(RemotePath("/site.zip.filpart"), to: RemotePath("/site.zip"))
        let moves = fake.calls.filter { $0.first == "mv" }
        XCTAssertEqual(moves, [
            ["mv", "/site.zip", "/site.zip.filbak"],
            ["mv", "/site.zip.filpart", "/site.zip"],
            ["mv", "/site.zip.filbak", "//bin"],
        ])
    }

    /// Un envoi est suivi par son numéro chez le serveur, et sa progression monte avec lui.
    func testUploadFollowsTheServerTransferByTag() async throws {
        let source = FileManager.default.temporaryDirectory.appendingPathComponent("FilMega-\(UUID().uuidString)")
        try Data(count: 2_000).write(to: source)
        defer { try? FileManager.default.removeItem(at: source) }
        let polls = OSAllocatedUnfairLock(initialState: 0)
        let fake = FakeMega { command, arguments in
            switch command {
            case "put":
                XCTAssertEqual(arguments, ["-q", "--print-tag-at-start", source.path, "/a.bin.filpart"])
                return ok("Upload started: Tag = 42\n")
            case "transfers":
                XCTAssertTrue(arguments.contains("--only-uploads"))
                let n = polls.withLock { $0 += 1; return $0 }
                let rows = ["41|10.00% of 9 MB|ACTIVE", n == 1 ? "42|25.00% of 1.95 KB|ACTIVE" : n == 2 ? "42|80.00% of 1.95 KB|ACTIVE" : "42|100.00% of 1.95 KB|COMPLETED"]
                return ok("TAG|PROGRESS|STATE\n" + rows.joined(separator: "\n"))
            case "ls": return ok("----  1  2000  2026-11-27T09:00:00  a.bin.filpart\n")
            default: return ok()
            }
        }
        let seen = OSAllocatedUnfairLock(initialState: [Int64]())
        try await MegaProvider(connection: connection, password: "", runner: fake, poll: .milliseconds(5)).upload(source, to: RemotePath("/a.bin.filpart"), resumingAt: 0) { value in
            seen.withLock { $0.append(value) }
        }
        XCTAssertEqual(seen.withLock { $0 }, [500, 1_600, 2_000, 2_000])
    }

    func testFailedTransferAndShortArrivalAreErrors() async throws {
        let source = FileManager.default.temporaryDirectory.appendingPathComponent("FilMega-\(UUID().uuidString)")
        try Data(count: 2_000).write(to: source)
        defer { try? FileManager.default.removeItem(at: source) }
        let failing = FakeMega { command, _ in
            command == "put" ? ok("Upload started: Tag = 5") : command == "transfers" ? ok("5|3.00% of 1 KB|FAILED") : ok()
        }
        do {
            try await MegaProvider(connection: connection, password: "", runner: failing, poll: .milliseconds(5)).upload(source, to: RemotePath("/a.bin"), resumingAt: 0) { _ in }
            XCTFail("Un transfert refusé doit échouer")
        } catch {
            XCTAssertTrue(error.localizedDescription.contains("a.bin"))
        }
        // Sorti de la liste sans « COMPLETED » : on regarde ce qui est vraiment arrivé.
        let vanished = FakeMega { command, _ in
            command == "put" ? ok("Upload started: Tag = 6") : command == "ls" ? ok("----  1  1200  2026-11-27T09:00:00  a.bin\n") : ok()
        }
        do {
            try await MegaProvider(connection: connection, password: "", runner: vanished, poll: .milliseconds(5)).upload(source, to: RemotePath("/a.bin"), resumingAt: 0) { _ in }
            XCTFail("Un fichier incomplet doit échouer")
        } catch {
            XCTAssertEqual(error as? ProviderError, .incomplete(name: "a.bin", received: 1_200, expected: 2_000))
        }
    }

    @MainActor
    func testCancellingInFilCancelsOnTheServer() async throws {
        let source = FileManager.default.temporaryDirectory.appendingPathComponent("FilMega-\(UUID().uuidString)")
        try Data(count: 10).write(to: source)
        defer { try? FileManager.default.removeItem(at: source) }
        let fake = FakeMega { command, _ in
            command == "put" ? ok("Upload started: Tag = 77") : command == "transfers" ? ok("77|1.00% of 10 B|ACTIVE") : ok()
        }
        let provider = MegaProvider(connection: connection, password: "", runner: fake, poll: .milliseconds(5))
        let task = Task { try await provider.upload(source, to: RemotePath("/a.bin"), resumingAt: 0) { _ in } }
        try await Task.sleep(for: .milliseconds(60))
        task.cancel()
        _ = await task.result
        await waitUntil("annulé chez le serveur") { fake.calls.contains(["transfers", "-c", "77"]) }
    }

